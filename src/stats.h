#pragma once
#include <glib.h>

/* Статистика прослушиваний по URI трека.
 *
 * Нужна, чтобы строить «популярные треки исполнителя» с точки зрения самого
 * пользователя: полноценных глобальных чартов у плеера нет, поэтому популярность
 * считаем по числу запусков. Счётчики хранятся отдельно от кэша медиатеки
 * (кэш — это данные сканирования, а статистика переживает пересканирование). */

/* Загружает счётчики (вызывается один раз при старте). */
void  stats_load(void);
/* Сохраняет счётчики на диск (при закрытии окна). */
void  stats_save(void);
/* Учитывает запуск трека (+1 к счётчику). */
void  stats_on_play(const char *uri);
/* Число прослушиваний трека (0, если неизвестен). */
guint stats_get_plays(const char *uri);
